"""Profile the raw pulls and write docs/DATA_PROFILE.md (the numbers behind each data decision).

Usage: python scripts/profile.py
"""

import collections
import datetime as dt
import glob
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "DATA_PROFILE.md"


def resp(path):
    return json.load(open(path))["response"]


def base(slug):
    return slug.split(":")[0]


def main():
    lines = []
    w = lines.append

    # Daily rankings
    files = sorted(glob.glob(str(RAW / "rankings_daily" / "*.json")))
    rows, metas = [], []
    for f in files:
        r = resp(f)
        rows += r["data"]
        metas.append(r["meta"])
    first = dt.date.fromisoformat(min(m["start_date"] for m in metas))
    last = dt.date.fromisoformat(max(m["end_date"] for m in metas))
    have = {r["date"] for r in rows}
    expected = [first + dt.timedelta(i) for i in range((last - first).days + 1)]
    missing = [str(d) for d in expected if str(d) not in have]
    per_day = collections.Counter(r["date"] for r in rows)
    dups = sum(1 for v in collections.Counter((r["date"], r["model_permaslug"]) for r in rows).values() if v > 1)
    tok = collections.Counter()
    for r in rows:
        tok[r["model_permaslug"]] += int(r["total_tokens"])
    total = sum(tok.values())
    named = total - tok["other"]
    slugs = [s for s in tok if s != "other"]
    variants = collections.Counter(s.split(":")[1] for s in slugs if ":" in s)
    dated = sum(1 for s in slugs if re.search(r"-20\d{6}$", base(s)))
    stealth = sum(t for s, t in tok.items() if s.startswith(("stealth/", "openrouter/")))
    month = collections.Counter()
    for r in rows:
        month[r["date"][:7]] += int(r["total_tokens"])

    w("# Data profile")
    w("")
    w(f"Generated by `scripts/profile.py` from the raw pulls. The pulls' `as_of` dates: {', '.join(sorted({m['as_of'][:10] for m in metas}))}.")
    w("")
    w("## Daily model rankings (`rankings_daily/`)")
    w("")
    w("| Check | Value |")
    w("|---|---|")
    w(f"| Window | {first} to {last} ({len(expected)} days) |")
    w(f"| Days present | {len(have)}; missing: {', '.join(missing) or 'none'} |")
    w(f"| Rows per day | min {min(per_day.values())}, max {max(per_day.values())} (top 50 + one `other` row) |")
    w(f"| Duplicate (date, model) keys | {dups} |")
    w(f"| Distinct model slugs | {len(slugs)}; {dated} carry a release date suffix; variants: {dict(variants)} |")
    w(f"| Total tokens | {total / 1e15:.2f} quadrillion |")
    w(f"| `other` (outside each day's top 50) | {100 * tok['other'] / total:.1f}% of all tokens |")
    w(f"| Stealth and OpenRouter house models (no named lab) | {100 * stealth / named:.1f}% of named tokens |")
    w(f"| Tokens per month, first and last full month | {month[str(first)[:7]] / 1e12:.1f}T ({str(first)[:7]}) to {month[(last.replace(day=1) - dt.timedelta(days=1)).strftime('%Y-%m')] / 1e12:.1f}T ({(last.replace(day=1) - dt.timedelta(days=1)).strftime('%Y-%m')}) |")
    w("")

    # Prices: live list + monthly Wayback snapshots
    snaps = sorted(glob.glob(str(RAW / "models_wayback" / "*.json"))) + sorted(glob.glob(str(RAW / "models" / "*.json")))
    live = resp(sorted(glob.glob(str(RAW / "models" / "*.json")))[-1])["data"]
    live_keys = {k for m in live for k in (m.get("id"), m.get("canonical_slug")) if k}
    all_keys = {}
    for f in snaps:
        for m in resp(f)["data"]:
            for k in (m.get("id"), m.get("canonical_slug")):
                if k:
                    all_keys.setdefault(k, m)

    def priced(keys):
        return sum(t for s, t in tok.items() if s != "other" and (s in keys or base(s) in keys))

    w("## Model list and prices (`models/`, `models_wayback/`)")
    w("")
    w("| Check | Value |")
    w("|---|---|")
    w(f"| Live list today | {len(live)} models |")
    w(f"| Named tokens whose model is in today's list | {100 * priced(live_keys) / named:.1f}% (retired models drop out) |")
    w(f"| Monthly Internet Archive snapshots | {len(snaps) - 1} ({Path(snaps[0]).stem[:8]} to {Path(snaps[-2]).stem[:8]}) |")
    w(f"| Named tokens with a price in some snapshot | {100 * priced(set(all_keys)) / named:.1f}% |")
    w("")

    # Category monthly rankings
    cat_files = sorted(glob.glob(str(RAW / "rankings_category_month" / "*.json")))
    cats = sorted({Path(f).stem.rsplit("_", 2)[0] for f in cat_files})
    periods, edge = set(), []
    for f in cat_files:
        r = resp(f)
        start = r["meta"]["start_date"]
        for d in sorted({x["date"] for x in r["data"]}):
            if d < start:
                edge.append((Path(f).stem, d))
            else:
                periods.add(d)
    w("## Monthly rankings by task category (`rankings_category_month/`)")
    w("")
    w("| Check | Value |")
    w("|---|---|")
    w(f"| Categories | {len(cats)}: {', '.join(cats)} |")
    w(f"| Months with data | {min(periods)[:7]} to {max(periods)[:7]} ({len(periods)}) |")
    w(f"| Partial buckets before a pull's start date | {len(edge)} (dropped; each pull keeps only months inside its own window) |")
    for per in (min(p for p in periods if p >= "2026-01-01"), max(periods)):
        s = 0
        for f in cat_files:
            r = resp(f)
            s += sum(int(x["total_tokens"]) for x in r["data"] if x["date"] == per and x["date"] >= r["meta"]["start_date"])
        w(f"| Sum over categories vs daily total, {per[:7]} | {100 * s / month[per[:7]]:.0f}% (sampled estimates, top 50 per category) |")
    w("")

    # Apps, benchmarks, tasks
    app_files = sorted(glob.glob(str(RAW / "app_rankings_month" / "*.json")))
    apps = collections.Counter()
    for f in app_files:
        for x in resp(f)["data"]:
            apps[x["app_name"]] += int(x["total_tokens"])
    w("## Apps, benchmarks, task mix")
    w("")
    w("| Check | Value |")
    w("|---|---|")
    w(f"| App rankings | {len(app_files)} months x top 100; {len(apps)} distinct apps |")
    recent = collections.Counter()
    for r in rows:
        if r["date"] > str(last - dt.timedelta(days=90)) and r["model_permaslug"] != "other":
            recent[r["model_permaslug"]] += int(r["total_tokens"])
    for f in sorted(glob.glob(str(RAW / "benchmarks" / "*.json"))):
        b = resp(f)
        keys = {x["model_permaslug"] for x in b["data"]}
        cov = sum(t for s, t in recent.items() if s in keys or base(s) in keys) / sum(recent.values())
        w(f"| Benchmarks: {b['meta']['source']} | {len(b['data'])} rows, as of {b['meta']['as_of'][:10]}; covers {100 * cov:.0f}% of the last 90 days' named tokens |")
    t = resp(sorted(glob.glob(str(RAW / "task_classifications" / "*.json")))[-1])["data"]
    w(f"| Task classifications | one {t['window_days']}-day snapshot, as of {t['as_of']}; {len(t['classifications'])} task tags |")
    w("")
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
