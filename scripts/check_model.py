"""Integrity checks on data/model.duckdb; writes docs/MODEL_CHECKS.md and exits 1 if any check fails.

Usage: python scripts/build_model.py && python scripts/check_model.py
"""

import glob
import json
import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "MODEL_CHECKS.md"


def main():
    con = duckdb.connect(str(ROOT / "data" / "model.duckdb"), read_only=True)
    q = lambda sql: con.execute(sql).fetchone()
    raw_rows, raw_tokens = 0, 0
    for f in glob.glob(str(ROOT / "data" / "raw" / "rankings_daily" / "*.json")):
        d = json.load(open(f))["response"]["data"]
        raw_rows += len(d)
        raw_tokens += sum(int(x["total_tokens"]) for x in d)

    checks = []  # (name, passed, detail)

    def check(name, passed, detail):
        checks.append((name, bool(passed), detail))

    n, t = q("SELECT count(*), sum(tokens) FROM fct_model_day")
    check("Fact rows and tokens match the raw pulls", n == raw_rows and t == raw_tokens,
          f"{n:,} rows / {t:,} tokens vs raw {raw_rows:,} / {raw_tokens:,}")
    d, u = q("SELECT count(*), count(DISTINCT model_permaslug) FROM dim_model")
    check("dim_model has one row per slug", d == u, f"{d} rows, {u} distinct")
    orphan = q("SELECT count(*) FROM fct_model_day f ANTI JOIN dim_model m USING (model_permaslug)")[0]
    check("Every fact row finds its model", orphan == 0, f"{orphan} orphan rows")
    d, u = q("SELECT count(*), count(DISTINCT org_name) FROM dim_lab")
    check("dim_lab has one row per organization", d == u, f"{d} rows, {u} distinct")
    orphan = q("SELECT count(*) FROM dim_model m ANTI JOIN dim_lab l USING (org_name)")[0]
    check("Every model finds its organization", orphan == 0, f"{orphan} models without an organization row")
    pend_slugs, pend_share = q("""SELECT count(*) FILTER (WHERE m.org_name = 'Pending lookup'),
        sum(f.tokens) FILTER (WHERE m.org_name = 'Pending lookup') / sum(f.tokens)
        FROM fct_model_day f JOIN dim_model m USING (model_permaslug)""")
    check("Every named lab is in the sourced lookup", (pend_share or 0) == 0,
          f"{100 * (pend_share or 0):.2f}% of tokens still 'Pending lookup'")
    missing = q("SELECT count(*) FROM dim_date WHERE is_missing_day")[0]
    check("Missing days are flagged, not filled", missing == 2, f"{missing} days flagged")
    dev = q("SELECT max(abs(s - 1)) FROM (SELECT month, sum(token_share) s FROM mart_lab_month GROUP BY 1)")[0]
    check("Token shares sum to 100% every month", dev < 1e-9, f"max deviation {dev:.2e}")
    t2 = q("SELECT sum(tokens) FROM mart_lab_month")[0]
    check("Lab-month tokens add back to the fact table", t2 == raw_tokens, f"{t2:,} vs {raw_tokens:,}")
    dev = q("SELECT max(abs(s - 1)) FROM (SELECT month, sum(spend_share) s FROM mart_lab_month GROUP BY 1)")[0]
    check("Spend shares sum to 100% every month", dev < 1e-9, f"max deviation {dev:.2e}")
    cov = con.execute("""SELECT mm.price_match, sum(mm.tokens) / (SELECT sum(tokens) FROM mart_model_month
        WHERE model_permaslug <> 'other') FROM mart_model_month mm WHERE model_permaslug <> 'other'
        GROUP BY 1 ORDER BY 2 DESC""").fetchall()
    unpriced = sum(s for k, s in cov if k in ("none", None))
    check("At least 95% of named tokens have a price", unpriced <= 0.05,
          "; ".join(f"{k}: {100 * s:.1f}%" for k, s in cov))
    ow = q("""SELECT sum(f.tokens) FILTER (WHERE m.open_weights IS NOT NULL) / sum(f.tokens)
        FROM fct_model_day f JOIN dim_model m USING (model_permaslug)
        WHERE NOT m.is_stealth AND f.model_permaslug <> 'other'""")[0]
    check("Open-weight status known for at least 90% of named, non-stealth tokens", ow >= 0.9, f"{100 * ow:.1f}% known")
    lo = q("SELECT min(month) FROM mart_category_month")[0]
    check("Category data has no partial edge buckets", str(lo) >= "2025-05-01", f"first month {lo}")
    bad = q("SELECT count(*) FROM mart_launch_weekly WHERE avg_daily_share < 0 OR avg_daily_share > 1")[0]
    check("Launch-curve shares are between 0 and 1", bad == 0, f"{bad} bad rows")
    used = q("SELECT count(*) FILTER (WHERE tokens_90d > 0), count(*) FROM mart_quality_price_90d")
    check("Benchmark rows join to usage", used[0] > 0, f"{used[0]} of {used[1]} benchmarked models have 90-day usage")

    lines = ["# Model checks", "", "Generated by `scripts/check_model.py`.", "",
             "| Check | Result | Detail |", "|---|---|---|"]
    lines += [f"| {n} | {'PASS' if p else 'FAIL'} | {d} |" for n, p, d in checks]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())
    sys.exit(0 if all(p for _, p, _ in checks) else 1)


if __name__ == "__main__":
    main()
